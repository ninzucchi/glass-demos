export function pickerIconMatchesQuery(name: string, query: string): boolean {
  const tokens = query
    .trim()
    .toLowerCase()
    .split(/[\s/_]+/)
    .filter(Boolean);
  if (tokens.length === 0) return true;
  const n = name.toLowerCase();
  return tokens.every((t) => n.includes(t));
}
